-- ---------------------------------------------------------------------
-- إخفاء ميزة "البث المباشر" مؤقتًا (تُفعَّل لاحقًا من لوحة الأدمن)
-- ---------------------------------------------------------------------
-- القرار: كود LiveKit والبث المباشر (الشاشات، الـ hooks، الـ Edge
-- Functions، جدول lives) كله يفضل زي ما هو بدون أي حذف — بس الميزة
-- تختفي من واجهة المستخدم لحد ما الأدمن يفعّلها.
--
-- التطبيق بيقرأ public.feature_flags (key = 'live') ويخفي بناءً عليه:
--   * كارت "اطلع اللايف" + شريط "يبث مباشرة الآن" فى صفحة القائمة
--   * تاب "لايفات" فى صفحة إدارة الحساب
--   * قسم "بثوث مباشرة" فى صفحة المعلن
--   * مسارات /live/* نفسها (حارس فى app/live/_layout.tsx)
--
-- للتفعيل لاحقًا: لوحة الأدمن → "الميزات العامة للمنصة" → مفتاح
-- "البث المباشر". (أو يدويًا: update public.feature_flags
--   set enabled = true where key = 'live';)
--
-- الـ upsert بدل update عادي: لو الصف مش موجود لأي سبب (قاعدة بيانات
-- جديدة لسه ما اتزرعش فيها seed) بيتنشأ معطّل، ولو موجود بيتحدّث. ترجّع
-- لـ trigger التدقيق (audit_feature_flag_update) صف بـ actor_id = null
-- (المهاجرة مش شغّالة بجلسة أدمن) — الـ actor_id nullable، فمفيش مشكلة.
insert into public.feature_flags (key, name, description, enabled)
values (
  'live',
  'البث المباشر',
  'إظهار البث المباشر للمستخدمين: زر "اطلع لايف" فى القائمة، تاب "لايفات" فى الحساب، وبثوث المعلن. معطّل حاليًا.',
  false
)
on conflict (key) do update
  set enabled = false,
      description = excluded.description,
      updated_at = now();
