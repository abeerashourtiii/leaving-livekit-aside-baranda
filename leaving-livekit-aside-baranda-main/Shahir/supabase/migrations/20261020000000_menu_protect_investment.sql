-- كارت «وكيلك القانونى» فى القائمة اتغيّر اسمه لـ «احمي استثمارك» (الصورة الجديدة فى assets/menu-icons/legal_card*.png):
--  • title العنصر  : «وكيلك القانوني» → «احمي استثمارك» (subtitle/أيقونة/لون/إجراء الواتساب كما هى).
--  • رسالة الواتساب الجاهزة: بنبدّل عبارة «(وكيلك القانوني)» بـ «(احمي استثمارك)» جوه النص الحالى (من غير ما نكتب فوق أى تعديل
--    للأدمن على رقم/نص الرسالة).
-- التطبيق نفسه بيتعرّف على الكارت بالعنوان الجديد والقديم وبمفتاح الأيقونة scale، فالتحديث آمن فى أى ترتيب (حتى لو الـ migration اتأخر).

update public.menu_items
   set title = 'احمي استثمارك',
       action_value = replace(action_value, '(وكيلك القانوني)', '(احمي استثمارك)')
 where icon_key = 'scale'
   and regexp_replace(title, '[\u064B-\u065F\u0640]', '', 'g') in ('وكيلك القانوني', 'وكيلك القانونى');
